import streamlit as st
import pandas as pd
import re


# =========================================================
# 페이지 설정
# =========================================================
st.set_page_config(
    page_title="한 달 동안 같은 반찬이 얼마나 나올까?",
    page_icon="🥗",
    layout="wide"
)


# =========================================================
# 메뉴 이름 정리
# =========================================================
def clean_menu(menu):

    menu = str(menu)

    # <br>, <br/>, <br /> → 줄바꿈
    menu = re.sub(
        r"<br\s*/?>",
        "\n",
        menu,
        flags=re.IGNORECASE
    )

    # HTML 태그 제거
    menu = re.sub(
        r"<[^>]+>",
        "",
        menu
    )

    # 알레르기 번호 제거
    # 예:
    # 김치(5.6)
    # 계란말이(1.2.5)
    # 고등어(1,5,6)
    menu = re.sub(
        r"\(\s*\d+(?:\s*[.,]\s*\d+)*\s*\)",
        "",
        menu
    )

    return menu


# =========================================================
# 메뉴 이름을 비교하기 위한 정리
# =========================================================
def normalize_menu(menu):

    menu = clean_menu(menu)

    # 앞뒤 공백 제거
    menu = menu.strip()

    # 여러 공백을 하나로
    menu = re.sub(
        r"\s+",
        " ",
        menu
    )

    return menu


# =========================================================
# 급식 메뉴를 한 줄씩 분리
# =========================================================
def make_menu_rows(df):

    rows = []

    for _, row in df.iterrows():

        menu_text = clean_menu(
            row["메뉴"]
        )

        # 줄바꿈 기준으로 메뉴 분리
        menus = menu_text.split("\n")

        for menu in menus:

            menu = normalize_menu(menu)

            if not menu:
                continue

            rows.append(
                {
                    "날짜": row["날짜"],
                    "메뉴": menu
                }
            )

    if not rows:
        return pd.DataFrame(
            columns=[
                "날짜",
                "메뉴"
            ]
        )

    result = pd.DataFrame(rows)

    # -----------------------------------------------------
    # 같은 날짜에 같은 메뉴가 여러 번 기록된 경우
    # 한 번만 계산
    # -----------------------------------------------------
    result = result.drop_duplicates(
        subset=[
            "날짜",
            "메뉴"
        ]
    )

    return result


# =========================================================
# 제목
# =========================================================
st.title(
    "🥗 한 달 동안 같은 반찬이 얼마나 나올까?"
)

st.write(
    "선택한 한 달의 급식 메뉴를 분석하여 "
    "같은 메뉴가 여러 날에 걸쳐 얼마나 반복해서 등장했는지 확인합니다."
)

st.divider()


# =========================================================
# 학교 선택 여부 확인
# =========================================================
if "school_code" not in st.session_state:

    st.warning(
        "먼저 첫 화면에서 학교를 선택해 주세요."
    )

    st.stop()


# =========================================================
# 급식 데이터 확인
# =========================================================
if "meal_df" not in st.session_state:

    st.warning(
        "먼저 첫 화면에서 분석할 연도와 월의 급식을 불러와 주세요."
    )

    st.stop()


# =========================================================
# 학교 정보
# =========================================================
school_name = st.session_state[
    "school_name"
]

year = st.session_state.get(
    "meal_year"
)

month = st.session_state.get(
    "meal_month"
)

df = st.session_state[
    "meal_df"
].copy()


st.info(
    f"현재 분석 학교: **{school_name}**  \n"
    f"분석 기간: **{year}년 {month}월**"
)


# =========================================================
# 메뉴 데이터 만들기
# =========================================================
menu_df = make_menu_rows(df)


if menu_df.empty:

    st.warning(
        "분석할 메뉴 데이터가 없습니다."
    )

    st.stop()


# =========================================================
# 메뉴별 등장 횟수 계산
# =========================================================
result = (
    menu_df
    .groupby("메뉴")
    .agg(
        나온횟수=("날짜", "nunique")
    )
    .reset_index()
)


# =========================================================
# 메뉴별 등장 날짜 계산
# =========================================================
date_map = (
    menu_df
    .groupby("메뉴")["날짜"]
    .apply(
        lambda dates: ", ".join(
            f"{day}일"
            for day in sorted(
                dates.dt.day.unique()
            )
        )
    )
    .reset_index(
        name="나온날짜"
    )
)


# =========================================================
# 등장 횟수 + 날짜 합치기
# =========================================================
result = result.merge(
    date_map,
    on="메뉴",
    how="left"
)


# =========================================================
# 많이 나온 메뉴부터 정렬
# =========================================================
result = result.sort_values(
    by=[
        "나온횟수",
        "메뉴"
    ],
    ascending=[
        False,
        True
    ]
).reset_index(drop=True)


# =========================================================
# 순위
# =========================================================
result.insert(
    0,
    "순위",
    range(
        1,
        len(result) + 1
    )
)


# =========================================================
# 결과 표
# =========================================================
st.header(
    "📋 메뉴별 전체 등장 횟수"
)

st.caption(
    "같은 메뉴가 같은 날 여러 번 기록되어도 "
    "한 번의 등장으로 계산했습니다."
)


st.dataframe(
    result[
        [
            "순위",
            "메뉴",
            "나온횟수",
            "나온날짜"
        ]
    ],
    use_container_width=True,
    hide_index=True
)


# =========================================================
# 그래프
# =========================================================
st.divider()

st.header(
    "📊 가장 자주 나온 메뉴 TOP 10"
)


chart_df = result.head(10).copy()

# 그래프에서는 위에서부터 많이 나오도록 정렬
chart_df = chart_df.sort_values(
    "나온횟수",
    ascending=True
)


st.bar_chart(
    chart_df.set_index(
        "메뉴"
    )["나온횟수"]
)


# =========================================================
# 반복 등장 메뉴 수
# =========================================================
st.divider()

st.header(
    "🔁 반복해서 나온 메뉴"
)


repeated_df = result[
    result["나온횟수"] >= 2
].copy()


if repeated_df.empty:

    st.info(
        "선택한 달에는 2번 이상 반복해서 나온 메뉴가 없습니다."
    )

else:

    st.write(
        f"전체 **{len(result)}개 메뉴** 중 "
        f"**{len(repeated_df)}개 메뉴**가 "
        "2번 이상 등장했습니다."
    )


# =========================================================
# 가장 많이 나온 메뉴
# =========================================================
st.divider()

st.header(
    "💡 이 그래프로 알 수 있는 것"
)


top = result.iloc[0]


st.write(
    f"**{year}년 {month}월 {school_name}**의 급식을 분석한 결과, "
    f"가장 많이 반복해서 나온 메뉴는 "
    f"**{top['메뉴']}**로 "
    f"총 **{top['나온횟수']}일**에 등장했습니다."
)


st.write(
    "표와 그래프를 통해 한 달 동안 어떤 메뉴가 "
    "반복적으로 급식에 등장했는지 비교할 수 있습니다."
)


st.caption(
    "※ 메뉴에 표시된 알레르기 유발물질 번호는 제거한 뒤 "
    "같은 메뉴인지 비교했습니다."
)
